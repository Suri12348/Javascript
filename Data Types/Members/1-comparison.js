//comparison operator
//(==,!=, >,>=, <, <=, ===)
console.log(1 == 1);//true
console.log(2 == 2);//true
console.log(3 == 2);//false

let number = 2;
console.log(number==2);//true
console.log(number != 2);//false
console.log(number >2 );//false
console.log(number >=2);//true
console.log(number <2 );//false
console.log(number <=2);//true
console.log(number ===2);//true

